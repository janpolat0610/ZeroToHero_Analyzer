"""Comment and question collector for Zero to Hero English Channel Analyzer.

Listens to messages sent in the linked Discussion Group (Supergroup).
"""

from datetime import datetime, timezone
import logging
from typing import Optional
from aiogram import Router, F
from aiogram.types import Message
from aiogram.enums import ChatType

from config import Settings
from database.crud import save_comment
from database.models import PostComment

logger = logging.getLogger("ZeroToHeroAnalyzer.CommentCollector")

router = Router(name="comment_collector")


def extract_reply_post_id(message: Message) -> Optional[int]:
    """Find the channel post ID this comment is replying to."""
    if not message.reply_to_message:
        return message.message_thread_id

    reply = message.reply_to_message

    # Check for direct automatic forward of the channel post
    if hasattr(reply, "forward_from_message_id") and reply.forward_from_message_id:
        return reply.forward_from_message_id

    # Check aiogram / Telegram Bot API 7.0+ forward_origin
    if hasattr(reply, "forward_origin") and reply.forward_origin:
        origin = reply.forward_origin
        if hasattr(origin, "message_id"):
            return getattr(origin, "message_id", None)

    # Fallback to the thread id or the replied message id
    return message.message_thread_id or reply.message_id


@router.message(F.chat.type.in_({ChatType.GROUP, ChatType.SUPERGROUP}))
async def handle_group_message(message: Message, settings: Settings) -> None:
    """Capture comments and questions from the linked Discussion Group."""
    chat_id = message.chat.id
    chat_username = message.chat.username

    # Skip automatic post forwards generated by Telegram (they are channel posts, not comments)
    if getattr(message, "is_automatic_forward", False):
        logger.debug(f"Skipping automatic channel post forward in group {chat_id}")
        return

    # Check if this group matches configured DISCUSSION_GROUP_ID if set
    if settings.DISCUSSION_GROUP_ID:
        target = str(settings.DISCUSSION_GROUP_ID).strip()
        matched = False
        if target.startswith("@") and chat_username:
            matched = (chat_username.lower() == target.lstrip("@").lower())
        else:
            try:
                matched = (chat_id == int(target))
            except ValueError:
                pass

        if not matched:
            logger.debug(f"Ignoring message from group {chat_id} (@{chat_username}), not matching {target}")
            return

    # Extract comment text
    text = message.text or message.caption or ""
    if not text.strip():
        # User sent a sticker or media without text
        if message.sticker:
            text = f"[Sticker: {message.sticker.emoji or 'emoji'}]"
        elif message.voice:
            text = "[Ovozli xabar]"
        else:
            text = "[Media fayl]"

    reply_post_id = extract_reply_post_id(message)
    msg_date = message.date.astimezone(timezone.utc) if message.date else datetime.now(timezone.utc)

    user_id = message.from_user.id if message.from_user else None
    user_fullname = message.from_user.full_name if message.from_user else None
    user_username = message.from_user.username if message.from_user else None

    comment = PostComment(
        message_id=message.message_id,
        chat_id=chat_id,
        reply_to_post_id=reply_post_id,
        text=text.strip(),
        user_id=user_id,
        user_fullname=user_fullname,
        user_username=user_username,
        date=msg_date
    )

    success = await save_comment(settings.DATABASE_PATH, comment)
    if success:
        logger.info(
            f"💬 Saved comment #{message.message_id} in '{message.chat.title}' "
            f"from {user_fullname} (Reply to post #{reply_post_id})"
        )
    else:
        logger.debug(f"Comment #{message.message_id} already exists or was skipped.")
